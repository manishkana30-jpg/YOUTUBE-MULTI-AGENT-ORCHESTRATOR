import { google } from 'googleapis';
import fs from 'fs';
import { costTracker } from './cost-tracker.js';

// Token refresh engine
export const youtubeAuthRefresh = {
  lastRefreshTime: Date.now(),

  async ensureValidToken(auth) {
    if (!auth) return;
    try {
      const tokenInfo = await auth.getAccessToken();
      // Refresh if expires in next 5 minutes
      if (tokenInfo?.res?.data?.expiry_date && (tokenInfo.res.data.expiry_date - Date.now() < 5 * 60 * 1000)) {
        console.log('[YouTube Auth] Token expiring within 5 minutes. Refreshing accessToken...');
        await auth.refreshAccessToken();
        this.lastRefreshTime = Date.now();
      }
    } catch (err) {
      console.warn('[YouTube Auth] Token refresh check notice:', err.message);
    }
  }
};

